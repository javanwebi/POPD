export function buildAll869VisualEntries(): E869VisualEntry[] {
  const byIndex = new Map<number, E869VisualEntry>();
  for (const rule of VISUAL_RULES) {
    if (!PART_CLASS_SPECS[rule.partClass]) {
      throw new Error(`Unknown partClass in VISUAL_RULES: ${rule.partClass}`);
    }
    for (const idx of rule.indices) {
      if (byIndex.has(idx)) {
        throw new Error(`Duplicate visual rule for e(${idx}).png`);
      }
      byIndex.set(idx, {
        index: idx,
        fileName: `e(${idx}).png`,
        url: `/storage/products/catalog/e(${idx}).png`,
        partClass: rule.partClass,
        colorHint: rule.colorHint,
        subTypeHint: rule.subTypeHint,
        noteFa: rule.noteFa,
      });
    }
  }
  const list: E869VisualEntry[] = [];
  for (let i = 1; i <= 869; i++) {
    const entry = byIndex.get(i);
    if (!entry) {
      throw new Error(`Missing visual classification for e(${i}).png`);
    }
    list.push(entry);
  }
  return list;
}
